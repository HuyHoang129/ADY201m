# === Câu 3: Tỷ lệ đăng ký theo nhóm tuổi (Chuẩn INE Bồ Đào Nha) ===
query = """
SELECT
  CASE
    WHEN age < 25 THEN 'under25'
    WHEN age BETWEEN 25 AND 44 THEN '25–44'
    WHEN age BETWEEN 45 AND 64 THEN '45–64'
    ELSE 'over 65'
  END AS nhom_tuoi,
  COUNT(*) AS tong_so,
  ROUND(
    SUM(CASE WHEN y = 'yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*),
    2
  ) AS ty_le_dang_ky
FROM bank
GROUP BY
  CASE
    WHEN age < 25 THEN 1
    WHEN age BETWEEN 25 AND 44 THEN 2
    WHEN age BETWEEN 45 AND 64 THEN 3
    ELSE 4
  END
ORDER BY nhom_tuoi;
"""

# Kiểm tra kết nối — thay bằng cách bạn đã kết nối trước đó
# Ví dụ nếu dùng SQLAlchemy:
