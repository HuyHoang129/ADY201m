# === Tính toán với Pandas — Chuẩn INE ===

# 1. Phân nhóm tuổi theo chuẩn Viện Thống kê Bồ Đào Nha (INE)
df['nhom_tuoi'] = pd.cut(
    df['age'],
    bins=[0, 25, 45, 65, float('inf')],
    labels=['under25', '25–44', '45–64', 'over 65'],
    right=False  # Bao gồm biên dưới, không bao gồm biên trên → <25, 25–44, 45–64, ≥65
)

# 2. Tính tổng số và tỷ lệ đăng ký gửi tiền
p3 = df.groupby('nhom_tuoi', observed=False).agg(
    tong_so=('nhom_tuoi', 'count'),
    ty_le_dang_ky=('y', lambda x: round((x == 'yes').mean() * 100, 2))
).reset_index()

# 3. Sắp xếp lại thứ tự nhóm tuổi
thu_tu = ['under25', '25–44', '45–64', 'over 65']
p3['thu_tu'] = p3['nhom_tuoi'].apply(lambda x: thu_tu.index(x))
p3 = p3.sort_values('thu_tu').drop(columns='thu_tu').reset_index(drop=True)

# 4. In kết quả
print("=== Kết quả Phân tích Tỷ lệ Đăng ký theo Nhóm Tuổi ===")
