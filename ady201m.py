query = """
SELECT
  marital AS tinh_trang_hon_nhan,
  COUNT(*) AS tong_so,
  SUM(CASE WHEN y = 'yes' THEN 1 ELSE 0 END) AS so_dang_ky,
  ROUND(
    SUM(CASE WHEN y = 'yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*),
    2
  ) AS ty_le_dang_ky
FROM bank
GROUP BY marital
ORDER BY ty_le_dang_ky DESC;
"""

pd.read_sql_query(query, conn)

# === Python/pandas ===
py1 = df.groupby('marital').agg(
    tong_so=('marital', 'count'),
    so_dang_ky=('y', lambda x: (x == 'yes').sum())
).reset_index()  # Đặt lại cột bình thường

# Tính tỷ lệ
py1['ty_le_dang_ky'] = round(py1['so_dang_ky'] / py1['tong_so'] * 100, 2)

# Sắp xếp + đặt lại chỉ số liên tục từ 0
