from functools import partial

def build_smote_pipeline(base_model, scale_data=True):
    """
    Xây dựng ML Pipeline dùng chung cho 5 mô hình.

    Mục đích:
    - Chọn 20 đặc trưng có thông tin cao nhất.
    - Chuẩn hóa dữ liệu nếu cần.
    - Xử lý mất cân bằng bằng SMOTE + Tomek Links.
    - Đảm bảo các bước được fit riêng trong mỗi CV fold.
    """

    steps = [
        # Chọn đặc trưng dựa trên training fold.
        # Không chọn trên toàn bộ dataset vì sẽ gây data leakage.
        (
            "feature_selection",
            SelectKBest(
                score_func=partial(
                    mutual_info_classif,
                    random_state=SEED
                ),
                k=20
            )
        )
    ]

    # StandardScaler đặc biệt hữu ích cho Logistic Regression.
    # Scale trước SMOTE vì SMOTE sử dụng khoảng cách giữa các mẫu.
    # Mô hình cây thường không cần scale để học.
    if scale_data:
        steps.append(("scaler", StandardScaler()))

    # SMOTE tạo thêm mẫu lớp thiểu số.
    # Tomek Links làm sạch một số cặp mẫu gần ranh giới.
    # imblearn Pipeline chỉ resample phần train của mỗi fold.
    steps.append((
        "smote_tomek",
        SMOTETomek(
            smote=SMOTE(
                k_neighbors=5,
                sampling_strategy=0.7,
                random_state=SEED
            ),
            tomek=TomekLinks(),
            random_state=SEED
        )
    ))

    # clone giúp mỗi lần huấn luyện có một model độc lập.
    steps.append(("model", clone(base_model)))

    return ImbPipeline(steps)



