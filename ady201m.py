    subset = test_analysis.head(n_selected)

    # Số khách thực sự đăng ký trong top-k.
    captured_pos = subset["actual"].sum()

    # Precision@k: tỷ lệ đăng ký trong nhóm được gọi.
    precision_at_k = captured_pos / n_selected

    # Recall@k: tỷ lệ khách đăng ký tìm thấy trong top-k.
    recall_at_k = captured_pos / total_actual_positive

    # Lift@k: hiệu quả so với gọi ngẫu nhiên.
    baseline = total_actual_positive / len(test_analysis)
    lift_at_k = precision_at_k / baseline

    # Số cuộc gọi tiết kiệm so với gọi toàn bộ danh sách.
    calls_reduced = 1 - n_selected / len(test_analysis)

    topk_summary.append({
        "Top (%)": round(frac * 100, 1),
        "Calls": n_selected,
        "Subscribers": int(captured_pos),
        "Precision@k": round(precision_at_k, 4),
        "Recall@k": round(recall_at_k, 4),
        "Lift@k": round(lift_at_k, 2),
        "Calls reduced (%)": round(calls_reduced * 100, 2)
    })


